# Python Function Practice

def greet(name):
    return f"Hello, {name}!"


def add(a, b):
    return a + b


def is_even(number):
    return number % 2 == 0


def find_max(a, b, c):
    return max(a, b, c)


print(greet("Nivetha"))
print("Sum:", add(10, 20))
print("Is 8 even?", is_even(8))
print("Maximum:", find_max(10, 25, 15))
